  // English unless Chinese was chosen explicitly; the system or browser language is not consulted.
  const lang = store.get('agentchat.lang') === 'zh' ? 'zh' : 'en';
  const has = Object.prototype.hasOwnProperty;
  // t('发给 {0}', names): the English text when English is chosen, else the Chinese key.
  function t(zh, ...args) {
    const text = lang === 'en' && has.call(EN, zh) ? EN[zh] : zh;
    if (!args.length) return text;
    return text.replace(/\{(\d+)\}/g, (m, k) => (args[k] == null ? '' : String(args[k])));
  }
  function setLang(next) {
    if (next === lang || (next !== 'zh' && next !== 'en')) return;
    store.set('agentchat.lang', next);
    window.location.reload();
  }

  // Theme: an explicit choice wins, otherwise follow the system setting.
  const media = window.matchMedia ? window.matchMedia('(prefers-color-scheme: dark)') : null;
  const theme = () => {
    const chosen = store.get('agentchat.theme');
    return chosen === 'dark' || chosen === 'light' ? chosen : (media && media.matches ? 'dark' : 'light');
  };
  const applyTheme = () => document.documentElement.setAttribute('data-theme', theme());
  function setTheme(next) {
    if (next !== 'dark' && next !== 'light') return;
    store.set('agentchat.theme', next);
    applyTheme();
  }
  applyTheme();
  if (media && media.addEventListener) media.addEventListener('change', () => { if (!store.get('agentchat.theme')) applyTheme(); });
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';

  window.AgentChatI18n = { t, lang, setLang, EN };
